static bool matches(ChihiroGuestRW rw, uint32_t va, const uint8_t *sig,
                    uint32_t n)
{
    uint8_t have[32];

    return n <= sizeof(have) && rw(va, have, n, false) && !memcmp(have, sig, n);
}

bool chihiro_widescreen_apply(const char *executable, ChihiroGuestRW rw)
{
    bool candidate = false;

    if (!executable || !executable[0]) {
        return false;
    }
    for (unsigned p = 0; p < G_N_ELEMENTS(profiles); p++) {
        const WideProfile *profile = &profiles[p];
        bool valid = true;

        if (g_ascii_strcasecmp(executable, profile->executable)) {
            continue;
        }
        candidate = true;
        for (unsigned i = 0; valid && i < profile->guard_count; i++) {
            const WideGuard *g = &profile->guards[i];
            valid = matches(rw, g->va, g->bytes, g->size);
        }
        for (unsigned i = 0; valid && i < profile->target_count; i++) {
            const WideTarget *t = &profile->targets[i];
            valid = matches(rw, t->va, t->original, 4);
        }
        if (!valid) {
            continue;   /* OutRun 2 and SP share outrun2.xbe */
        }
        for (unsigned i = 0; i < profile->target_count; i++) {
            const WideTarget *t = &profile->targets[i];
            if (rw(t->va, (void *)t->wide, 4, true) &&
                matches(rw, t->va, t->wide, 4)) {
                continue;
            }
            /* Half a patch is worse than none: put everything back. */
            for (unsigned j = 0; j <= i; j++) {
                const WideTarget *r = &profile->targets[j];
                rw(r->va, (void *)r->original, 4, true);
            }
            fprintf(stderr, "Chihiro: widescreen patch for %s failed, rolled "
                    "back\n", profile->name);
            return false;
        }
        fprintf(stderr, "Chihiro: widescreen, %s patched to 16:9 (%u values)\n",
                profile->name, profile->target_count);
        return true;
    }
    if (candidate) {
        fprintf(stderr, "Chihiro: widescreen, %s is not a revision the patch "
                "knows, left at 4:3\n", executable);
    }
    return false;
}
